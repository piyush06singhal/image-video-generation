class FFmpegExecutionError(AppException):
    def __init__(self, message: str, details: Optional[Dict[str, Any]] = None):
        super().__init__(
            message=message,
            code="FFMPEG_EXECUTION_ERROR",
            status_code=500,
            details=details,
        )


# ── Colour grading ────────────────────────────────────────────────────────
# Each entry is the filter fragment inserted *after* unsharp and *before* the
# vignette/grain/format tail.
#
# Two deliberate design rules, both learned by measuring:
#
# * **Never blanket-darken.** Listing photography arrives already well exposed,
#   and the previous "warm luxury" stack pulled a typical interior down by about
#   30 luma levels while crushing 2% of the frame to black and darkening the
#   corners on top of that. A frame that is dimmer, with black corners and black
#   cinematic bars, is exactly what reads as *diluted*. These curves lift shadows
#   (a film print never sits on true black), hold the mids, and roll the top off
#   below clipping, so the result is brighter than the source, not dimmer.
# * **Contrast, not vignette.** Separation is bought with a mid-tone S and
#   `vibrance`, which leaves the picture whole; the vignette is left gentle
#   (PI/7) so it frames the shot rather than swallowing it.
#
# `curves` does the tonal shape per channel — that per-channel split-toning (warm
# highlights, cooler shadows) is what actually sells "graded" footage, and it is a
# built-in filter rather than a hand-rolled numpy pass.
_GRADE_FILTERS: Dict[str, str] = {
    "none": "",
    # colorbalance split options are shadows (r/g/b s), midtones (m) and
    # highlights (h); the previous "hm/hs/lm/ls" spelling does not exist and made
    # FFmpeg reject the whole filtergraph.
    "warm_luxury": (
        "curves=all='0/0.032 0.28/0.328 0.60/0.664 0.88/0.928 1/0.992'"
        ":r='0/0.028 0.5/0.512 1/1.0'"
        ":b='0/0.036 0.5/0.494 1/0.974',"
        "colorbalance=rs=.03:bs=-.04:rm=.01:bh=-.05:rh=.05,"
        "vibrance=intensity=0.16"
    ),
    # Late-afternoon sun: the most requested listing look, and warmer still than
    # warm_luxury, with the highlights pushed toward amber.
    "golden_hour": (
        "curves=all='0/0.030 0.28/0.332 0.60/0.676 0.88/0.940 1/0.994'"
        ":r='0/0.040 0.5/0.530 1/1.0'"
        ":b='0/0.024 0.5/0.480 1/0.956',"
        "colorbalance=rm=.03:rh=.06:bm=-.05:bh=-.07,"
        "vibrance=intensity=0.18"
    ),
    "cool_modern": (
        "curves=all='0/0.030 0.28/0.324 0.60/0.660 0.88/0.928 1/0.992'"
        ":r='0/0.030 0.5/0.494 1/0.980'"
        ":b='0/0.020 0.5/0.514 1/1.0',"
        "colorbalance=rs=-.03:bs=.03,"
        "vibrance=intensity=0.10"
    ),
    # Teal shadows against warm highlights — the classic blockbuster split-tone,
    # still lifted rather than crushed.
    "cinematic_teal": (
        "curves=all='0/0.024 0.30/0.314 0.62/0.650 0.88/0.912 1/0.990'"
        ":r='0/0.014 0.5/0.522 1/1.0'"
        ":b='0/0.034 0.5/0.486 1/0.966',"
        "vibrance=intensity=0.20"
    ),
    "noir": (
        "hue=s=0,"
        "curves=all='0/0.022 0.30/0.318 0.62/0.668 0.88/0.936 1/0.994',"
        "eq=contrast=1.08:gamma=1.05"
    ),
}

# ── Halation (the "bloom" option) ────────────────────────────────────────
# Only true highlights are allowed to glow (`_HALATION_GATE`), and the glow is
# built by squashing the frame horizontally, blurring, then stretching it back:
# this FFmpeg build's gblur has no per-axis sigma, and the wide, low smear it
# produces is the anamorphic halation a fast lens actually gives. Screening a
# blur of the *whole* frame instead — which is what this used to do — lifts every
# shadow into grey haze, and is a second way a cut reads as diluted.
# Only pixels above this level feed the glow. Measured against a black patch
# beside a blown highlight, this leaves the shadows *exactly* untouched (+0.0)
# while still lighting the wall next to the window, which is the whole point.
_HALATION_GATE = 0.62
# Opacity and spread are a measured compromise, swept on a real interior:
#
#   opacity  sigma  luma  contrast  detail  shadows(p1)
#   (none)     -    164.5   54.9     19.0     15
#    0.20     3.0   167.0   56.2     18.1     15
#    0.35     3.0   168.9   56.8     17.2     19
#    1.00     wide  169.3   49.8     10.5     46   <- the haze this replaced
#
# Full strength flattens contrast and halves the detail (and lifts the shadows to
# 46), because in a bright interior "near a highlight" is most of the frame. A
# tight, partly-opaque glow buys the warmth and separation of the middle rows and
# leaves the picture otherwise intact.
_HALATION_OPACITY = 0.30
_HALATION_SIGMA = 0.0028  # of the frame's short side, before the horizontal smear
_HALATION_SQUASH = 5

# TransitionStyle value -> xfade transition name.
# ``hblur`` and ``smoothleft`` are the motion-bridged cuts: they smear the
# outgoing frame instead of merely mixing it, so the eye reads one continuous
# move rather than two photographs swapping places.
