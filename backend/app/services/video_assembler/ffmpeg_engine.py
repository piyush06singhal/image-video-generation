    # ── room labels ──────────────────────────────────────────────────────
    def render_label_png(
        self,
        label: str,
        output_path: Path,
        height: int = 1080,
        counter: Optional[str] = None,
        progress: Optional[float] = None,
    ) -> Path:
        """Renders a transparent lower-third strip.

        Beyond the room name this carries a position counter ("03 / 08") and a thin
        progress line, so a viewer always knows where they are in the tour. Those
        two elements are most of what separates a listing clip from a home video.
        """
        scale = max(0.55, min(1.5, height / 1080.0))
        font = cv2.FONT_HERSHEY_TRIPLEX
        small_font = cv2.FONT_HERSHEY_SIMPLEX
        font_scale = 0.92 * scale
        thickness = max(1, int(2 * scale))
        text_size, _ = cv2.getTextSize(label, font, font_scale, thickness)

        counter_text = (counter or "").strip()
        counter_scale = 0.52 * scale
        counter_size = (
            cv2.getTextSize(counter_text, small_font, counter_scale, 1)[0] if counter_text else (0, 0)
        )

        pad_x, pad_y = int(30 * scale), int(20 * scale)
        bar_w = max(3, int(4 * scale))
        gap = int(18 * scale)
        track_h = max(2, int(3 * scale))
        track_gap = int(16 * scale)

        inner_w = bar_w + gap + text_size[0] + (gap + counter_size[0] if counter_text else 0)
        canvas_w = inner_w + pad_x * 2
        canvas_h = pad_y * 2 + text_size[1] + track_gap + track_h

        canvas = np.zeros((canvas_h, canvas_w, 4), np.uint8)
        # Soft translucent plate so labels stay legible over bright and dark rooms.
        canvas[:, :, 0:3] = 8
        canvas[:, :, 3] = 118

        baseline = pad_y + text_size[1]
        # Gold accent bar, flush with the text height.
        cv2.rectangle(
            canvas,
            (pad_x, pad_y - int(2 * scale)),
            (pad_x + bar_w, baseline + int(2 * scale)),
            (83, 168, 212, 255),
            -1,
        )

        cursor = pad_x + bar_w + gap
        cv2.putText(
            canvas, label, (cursor, baseline), font, font_scale, (255, 255, 255, 255), thickness, cv2.LINE_AA
        )
        cursor += text_size[0]
        if counter_text:
            cursor += gap
            cv2.putText(
                canvas, counter_text, (cursor, baseline - int(3 * scale)),
                small_font, counter_scale, (170, 186, 200, 255), 1, cv2.LINE_AA,
            )

        # Progress line: a dim track with a gold fill showing tour position.
        track_y = canvas_h - pad_y - track_h + int(2 * scale)
        cv2.rectangle(
            canvas, (pad_x, track_y), (canvas_w - pad_x, track_y + track_h), (255, 255, 255, 58), -1
        )
        if progress is not None:
            filled = int((canvas_w - pad_x * 2) * max(0.0, min(1.0, float(progress))))
            if filled > 0:
                cv2.rectangle(
                    canvas, (pad_x, track_y), (pad_x + filled, track_y + track_h),
                    (83, 168, 212, 255), -1,
                )

        output_path.parent.mkdir(parents=True, exist_ok=True)
        cv2.imwrite(str(output_path), canvas)
        return output_path

    def apply_room_label(
        self,
        input_path: Path,
        output_path: Path,
        label: str,
        width: int,
        height: int,
        fps: float,
        hold_seconds: float = 2.4,
        counter: Optional[str] = None,
        progress: Optional[float] = None,
    ) -> Path:
        """Burns a lower-third room name onto a clip, sliding in as it fades up."""
        if not label.strip():
            return self.normalize_clip(input_path, output_path, width, height, fps)

        output_path.parent.mkdir(parents=True, exist_ok=True)
        meta = self.probe_video(input_path)
        clip_duration = max(0.5, meta["duration_seconds"])

        label_png = self._temp_in(output_path.parent, ".label.png")
        try:
            self.render_label_png(
                label, label_png, height=height, counter=counter, progress=progress
            )

            fade_in_at = 0.45
            fade_len = 0.55
            # Hold, then fade out before the clip ends (and again before a crossfade
            # begins, so a label never overlaps the next room).
            fade_out_at = min(clip_duration - 0.9, fade_in_at + hold_seconds)
            if fade_out_at <= fade_in_at + fade_len:
                fade_out_at = max(fade_in_at + fade_len + 0.1, clip_duration - 1.0)

            margin_x = max(48, int(width * 0.045))
            margin_y = max(48, int(height * 0.075))
            # `-h` refers to the overlay's own height, so the strip sits a fixed
            # distance above the bottom edge regardless of resolution. The extra
            # term lifts the strip into place over the first half second; it is
            # written without commas because FFmpeg treats a comma as a filter
            # separator inside a filtergraph.
            overlay_y = (
                f"{height - margin_y}-h"
                f"+(gt(0.50-t,0))*(0.50-t)*{max(24, int(height * 0.035))}"
            )
            graph = (
                f"[0:v]format=rgba,"
                f"fade=t=in:st={fade_in_at:.2f}:d={fade_len:.2f}:alpha=1,"
                f"fade=t=out:st={fade_out_at:.2f}:d={fade_len:.2f}:alpha=1[lbl];"
                f"[1:v][lbl]overlay={margin_x}:'{overlay_y}':format=auto,format=yuv420p[v]"
            )

            cmd = [
                self._ffmpeg_path,
                "-y",
                "-loop", "1",
                "-framerate", str(fps),
                "-i", str(label_png),
                "-i", str(input_path),
                "-filter_complex", graph,
                "-map", "[v]",
                "-t", f"{clip_duration:.3f}",
                *self._ENCODE_ARGS,
                "-an",
                str(output_path),
            ]
            self._run(cmd, f"burning room label '{label}'")
        finally:
            label_png.unlink(missing_ok=True)

        return output_path

    # ── grading / final conform ───────────────────────────────────────────
    def grade_and_conform(
        self,
        input_path: Path,
        output_path: Path,
        width: int,
        height: int,
        fps: float,
        color_grade: str = "none",
        vignette: bool = False,
        film_grain: bool = False,
        sharpen: bool = True,
        letterbox: bool = False,
        bloom: bool = False,
    ) -> Path:
        """Single pass that conforms the frame and applies the cinematic look.

        ``letterbox`` adds scope-style bars for a filmic frame; it is ignored on
        portrait/square output, where bars would only eat useful picture.
        ``bloom`` screens a heavily blurred copy back over the frame for the soft
        highlight halation a fast lens produces — the cheapest single effect for
        making graded footage look like it cost more than it did.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)

        filters: List[str] = [self._cover_filter(width, height)]
        if sharpen:
            filters.append("unsharp=5:5:0.85:5:5:0.0")
        grade = _GRADE_FILTERS.get(color_grade, "")
        if grade:
            filters.append(grade)
        if vignette:
            # Gentle: it should frame the shot, not swallow the corners.
            filters.append("vignette=PI/7")
        if film_grain:
            filters.append("noise=alls=5:allf=t+u")
        filters.append(f"fps={fps}")
        filters.append("format=yuv420p")

        # Scope bars are applied last, *after* the bloom. Screening a glow over a
        # frame lifts true black to mid grey, so bars drawn before it would come out
        # washed rather than black.
        bars: List[str] = []
        if letterbox and width > height:
            bar = int(height * 0.055)
            bars.append(f"drawbox=x=0:y=0:w={width}:h={bar}:color=black@1:t=fill")
            bars.append(f"drawbox=x=0:y={height - bar}:w={width}:h={bar}:color=black@1:t=fill")

        if bloom:
            # Needs two streams, so a filtergraph rather than a linear chain.
            sigma = max(1.5, min(width, height) * _HALATION_SIGMA)
            squash = max(2, width // _HALATION_SQUASH)
            graph = (
                f"[0:v]{','.join(filters)}[pre];"
                f"[pre]split[base][glowsrc];"
                # Gate the glow to the highlights before blurring: halation comes
                # from bright areas bleeding, and keeps shadows and black bars from
                # being lifted into a milky haze.
                f"[glowsrc]colorlevels=rimin={_HALATION_GATE}:gimin={_HALATION_GATE}"
                f":bimin={_HALATION_GATE},"
                f"scale={squash}:{height},gblur=sigma={sigma:.1f},scale={width}:{height}[glow];"
                f"[base][glow]blend=all_mode=screen:all_opacity={_HALATION_OPACITY}"
                + ("," + ",".join(bars) if bars else "")
                + ",format=yuv420p[outv]"
            )
            cmd = [
                self._ffmpeg_path,
                "-y",
                "-i", str(input_path),
                "-filter_complex", graph,
                "-map", "[outv]",
                *self._ENCODE_ARGS,
                "-an",
                str(output_path),
            ]
        else:
            cmd = [
                self._ffmpeg_path,
                "-y",
                "-i", str(input_path),
                "-vf", ",".join(filters + bars),
                *self._ENCODE_ARGS,
                "-an",
                str(output_path),
            ]

        logger.info(
            f"Grading walkthrough (grade={color_grade}, vignette={vignette}, grain={film_grain}, "
            f"letterbox={letterbox}, bloom={bloom}) -> {width}x{height}@{fps}"
        )
        self._run(cmd, "grading the walkthrough")
        return output_path

    # ── music ────────────────────────────────────────────────────────────
    def synthesize_music(
        self,
        duration_seconds: float,
        style: str,
        output_path: Path,
        volume: float = 0.28,
        fade_in: float = 2.0,
        fade_out: float = 3.0,
        cut_times: Optional[List[float]] = None,
        opening_riser: bool = False,
        final_impact: bool = False,
    ) -> Path:
        """Composes and encodes the score cue, with sound design on the cuts.

        The music itself is written by :mod:`music_engine` (chords, bass,
        arpeggio, percussion and reverb — all generated, nothing licensed), then
        transcoded to AAC and loudness-normalised so every mood lands at the same
        perceived level.

        ``cut_times`` are the assembly's transition positions: they drive the
        incidental layer (a whoosh on every cut, an optional riser into the first
        shot and a closing button on the end card), which is what makes the edit
        feel produced rather than assembled.

        ``volume`` is accepted for API compatibility but is **not** applied here:
        the mix stage owns the single user-facing score level. Applying it in both
        places is what used to make the score effectively inaudible (0.28 * 0.28).
        ``fade_in``/``fade_out`` likewise live in the composer, where the curve is
        exact; they are kept for the same compatibility reason.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        duration = max(1.0, float(duration_seconds))

        accents = music_engine.plan_accents(
            duration,
            cut_times or [],
            opening_riser=opening_riser,
            final_impact=final_impact,
        )

        wav_path = self._temp_in(output_path.parent, ".score.wav")
        try:
            music_engine.write_wav(
                music_engine.render(duration, style, accents=accents), wav_path
            )
            cmd = [
                self._ffmpeg_path,
                "-y",
                "-i", str(wav_path),
                # Single-pass loudness normalisation so a quiet ballad and a
                # driving reel sit at the same level under the picture.
                "-af", "loudnorm=I=-19:TP=-1.5:LRA=9",
                "-c:a", "aac",
                "-b:a", "192k",
                str(output_path),
            ]
            logger.info(
                f"Composing '{style}' score cue ({duration:.1f}s) with "
                f"{len(accents)} incidental(s) over {len(cut_times or [])} cut(s)"
            )
            self._run(cmd, "encoding the composed score")
        finally:
            wav_path.unlink(missing_ok=True)
        return output_path

    # ── assembly ─────────────────────────────────────────────────────────
    def concatenate_clips(
        self,
        clip_paths: List[Path],
        output_path: Path,
        transitions: Optional[List[str]] = None,
        crossfade_duration: float = 0.35,
        transition_style: Optional[str] = None,
    ) -> Path:
        """
        Concatenates ordered clips using either straight cuts or xfade transitions.

        ``transition_style`` (a RenderOptions TransitionStyle value) applies one
        consistent transition between every pair and takes precedence over the
        per-scene ``transitions`` list, which the plan used to fill with mostly
        ``straight_cut`` values.
        """
        if not clip_paths:
            raise ValueError("No video clips provided for concatenation.")

        output_path.parent.mkdir(parents=True, exist_ok=True)
        per_pair: List[str] = []
        if transition_style and transition_style in _XFADE_NAMES:
            per_pair = [_XFADE_NAMES[transition_style]] * max(0, len(clip_paths) - 1)
        elif transitions:
            per_pair = [_XFADE_NAMES.get(t, None) or "cut" for t in transitions]

        xfade_pairs = [t for t in per_pair if t != "cut"]

        if len(clip_paths) == 1 or not xfade_pairs:
            return self._concat_demuxer(clip_paths, output_path)

        durations = [self.probe_video(cp)["duration_seconds"] for cp in clip_paths]
        # An xfade longer than the shot it sits in collapses the timeline; clamp it.
        shortest = min(durations)
        xd = max(0.1, min(crossfade_duration, shortest * 0.5))

        inputs: List[str] = []
        for cp in clip_paths:
            inputs.extend(["-i", str(cp)])

        filter_parts: List[str] = []
        current = "[0:v]"
        offset = durations[0] - xd
        cut_times: List[float] = []

        for i in range(1, len(clip_paths)):
            nxt = f"[{i}:v]"
            out = f"[v{i}]" if i < len(clip_paths) - 1 else "[outv]"
            pair = per_pair[i - 1] if i - 1 < len(per_pair) else "cut"

            if pair != "cut" and offset > 0.05:
                filter_parts.append(
                    f"{current}{nxt}xfade=transition={pair}:duration={xd:.3f}:offset={offset:.3f}{out}"
                )
                # Midpoint of the transition is where the two shots are equally
                # present — the moment a whoosh should peak.
                cut_times.append(offset + xd * 0.5)
                offset = offset + durations[i] - xd
            else:
                filter_parts.append(f"{current}{nxt}concat=n=2:v=1:a=0{out}")
                cut_times.append(offset)
                offset = offset + durations[i]
            current = out

        self._last_transition_times = cut_times

        cmd = [
            self._ffmpeg_path,
            "-y",
            *inputs,
            "-filter_complex", ";".join(filter_parts),
            "-map", "[outv]",
            *self._ENCODE_ARGS,
            "-an",
            str(output_path),
        ]

        logger.info(f"Assembling {len(clip_paths)} clips with '{transition_style or 'plan'} transitions")
        proc = self._run(cmd, "assembling the walkthrough", tolerate=True)
        if proc.returncode != 0:
            # Keep the render alive, but never hide that the intended transitions
            # were dropped: the old silent fallback made it look like a success.
            logger.error(
                "Transition assembly failed; degrading to straight cuts. "
                f"stderr={proc.stderr[-400:] if proc.stderr else ''}"
            )
            return self._concat_demuxer(clip_paths, output_path)

        return output_path

    def last_transition_times(self) -> List[float]:
        """Cut positions of the most recent assembly, in output seconds."""
        return list(self._last_transition_times)

    def _concat_demuxer(self, clip_paths: List[Path], output_path: Path) -> Path:
        if len(clip_paths) == 1:
            self._last_transition_times = []
            return self.normalize_clip(clip_paths[0], output_path)

        # Straight-cut fallback still cuts, so still record where.
        cut_times: List[float] = []
        elapsed = 0.0
        for cp in clip_paths[:-1]:
            elapsed += self.probe_video(cp)["duration_seconds"]
            cut_times.append(elapsed)
        self._last_transition_times = cut_times

        concat_list_file = output_path.parent / f"concat_{hashlib.md5(str(output_path).encode()).hexdigest()[:8]}.txt"
        with open(concat_list_file, "w", encoding="utf-8") as f:
            for p in clip_paths:
                f.write(f"file '{p.resolve()}'\n")

        cmd = [
            self._ffmpeg_path,
            "-y",
            "-f", "concat",
            "-safe", "0",
            "-i", str(concat_list_file),
            *self._ENCODE_ARGS,
            "-an",
            str(output_path),
        ]
        proc = self._run(cmd, "concatenating clips", tolerate=True)
        concat_list_file.unlink(missing_ok=True)
        if proc.returncode != 0:
            raise FFmpegExecutionError(
                "Straight-cut concatenation failed", details={"stderr": proc.stderr[-500:]}
            )
        return output_path

    # ── audio mux ────────────────────────────────────────────────────────
    def add_background_audio(
        self,
        video_path: Path,
        audio_path: Path,
        output_path: Path,
        volume: float = 0.60,
    ) -> Path:
        """
        Mixes the score bed under the picture, truncated to the video length and
        faded out at the end.
        """
        if not audio_path.exists():
            raise FileNotFoundError(f"Audio file not found: {audio_path}")

        meta = self.probe_video(video_path)
        duration = meta["duration_seconds"]

        output_path.parent.mkdir(parents=True, exist_ok=True)
        fade_start = max(0.0, duration - 2.0)
        audio_filter = f"volume={volume},afade=t=out:st={fade_start:.2f}:d=2.0"

        cmd = [
            self._ffmpeg_path,
            "-y",
            "-i", str(video_path),
            "-i", str(audio_path),
            "-filter_complex", f"[1:a]{audio_filter}[aout]",
            "-map", "0:v",
            "-map", "[aout]",
            "-c:v", "copy",
            "-c:a", "aac",
            "-b:a", "192k",
            "-t", f"{duration:.3f}",
            "-movflags", "+faststart",
            str(output_path),
        ]

        logger.info(f"Mixing score bed into walkthrough at volume {volume}")
        self._run(cmd, "mixing the background score")
        return output_path

    # ── misc helpers used by the report ───────────────────────────────────
    def extract_frame(self, video_path: Path, at_seconds: float, output_path: Path) -> Path:
        """Writes a single frame to disk — used by the review page generator."""
        output_path.parent.mkdir(parents=True, exist_ok=True)
        cmd = [
            self._ffmpeg_path,
            "-y",
            "-ss", f"{max(0.0, at_seconds):.3f}",
            "-i", str(video_path),
            "-frames:v", "1",
            str(output_path),
        ]
        self._run(cmd, f"extracting a frame from {video_path.name}")
        return output_path


