"""FFmpeg/OpenCV engine for the assembled walkthrough.

This module owns every pixel that ends up in the final MP4 that is *not*
generated by an image-to-video provider. Phase 4 produced bare camera moves over
stills; this engine is what turns those moves into something that reads as a
produced film:

* **Conform** — every clip is cover-cropped (never letterboxed) to the project's
  exact target frame, so no black bars ever survive into the output.
* **Grade** — a real colour treatment (warm luxury / cool modern / cinematic teal
  / noir) plus optional vignette and film grain, applied as a single encode pass.
* **Branded cards** — intro and outro titles composited over a blurred, slowly
  drifting plate taken from the property's own photography, rather than the flat
  black card this used to render.
* **Room labels** — a lower-third burned onto each scene so viewers always know
  which space they are looking at.
* **Score** — a procedurally synthesised royalty-free bed (no licensed assets are
  shipped), ducked, faded and muxed against the picture.

Font note: OpenCV's built-in Hershey vector fonts are used instead of FFmpeg's
``drawtext`` because ``drawtext`` needs a font file, and no font file is
guaranteed to exist on an arbitrary host.
"""

